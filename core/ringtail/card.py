"""Render the detection card for a rule: cards/<rule-id>.md.

A card is generated, never hand-edited. It has three sources:

- the rule YAML (title, ATT&CK tags, log source, exact logic, false positives, references);
- a fresh test run (TP/FP results come from code, not from anyone's claim);
- cards/<rule-id>.yml: the human judgment code can't derive (goal, plain-English
  summary, triage steps). Later the AI loop will draft this file, validated like any
  other AI output.

Output is deterministic (no timestamps) so CI can fail when a committed card is stale.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml
from sigma.rule import SigmaRule

from ringtail.attack import TECHNIQUE_RE, default_index
from ringtail.testrunner import RuleReport, run_rule_tests

GENERATED_NOTE = "<!-- Generated by `ringtail card`. Do not edit: change the rule or cards/{id}.yml instead. -->"

_MODIFIER_PHRASES = {
    "contains": "contains",
    "startswith": "starts with",
    "endswith": "ends with",
    "re": "matches regex",
    "cidr": "is in network",
    "lt": "is less than",
    "lte": "is at most",
    "gt": "is greater than",
    "gte": "is at least",
    "exists": "exists:",
}
_MODIFIER_NOTES = {
    "windash": "also matches `/` and Unicode dash look-alikes in place of `-`",
    "base64": "value is base64-encoded",
    "base64offset": "value is base64-encoded at any offset",
    "cased": "case-sensitive",
    "wide": "UTF-16 encoded",
}


class CardNotesError(ValueError):
    """cards/<rule-id>.yml is missing or malformed."""


@dataclass
class CardNotes:
    goal: str
    summary: str
    triage: list[str]

    @classmethod
    def load(cls, path: Path) -> "CardNotes":
        if not path.is_file():
            raise CardNotesError(f"missing {path.as_posix()} (goal, summary, triage)")
        data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        return cls.from_dict(data, where=path.as_posix())

    @classmethod
    def from_dict(cls, data: Any, where: str = "card", min_triage: int = 1) -> "CardNotes":
        if not isinstance(data, dict):
            raise CardNotesError(f"{where} must be a mapping")
        goal, summary, triage = data.get("goal"), data.get("summary"), data.get("triage")
        if not isinstance(goal, str) or not goal.strip():
            raise CardNotesError(f"{where}: 'goal' must be a non-empty string")
        if not isinstance(summary, str) or not summary.strip():
            raise CardNotesError(f"{where}: 'summary' must be a non-empty string")
        if not isinstance(triage, list) or not triage or not all(isinstance(s, str) and s.strip() for s in triage):
            raise CardNotesError(f"{where}: 'triage' must be a non-empty list of strings")
        if len(triage) < min_triage:
            raise CardNotesError(f"{where}: 'triage' needs at least {min_triage} steps, got {len(triage)}")
        return cls(goal.strip(), summary.strip(), [s.strip() for s in triage])

    def to_dict(self) -> dict:
        return {"goal": self.goal, "summary": self.summary, "triage": list(self.triage)}


# ---------------------------------------------------------------------------
# Plain-English rendering of the exact detection logic (from the raw YAML, so modifiers
# like windash read as written rather than as their five expanded variants).


def _q(v: Any) -> str:
    if v is None:
        return "empty (null)"
    if isinstance(v, bool):
        return f"`{str(v).lower()}`"
    if isinstance(v, (int, float)):
        return f"`{v}`"
    return f"`'{v}'`"


def _field_line(key: str, value: Any) -> str:
    name, *mods = key.split("|")
    match_all = "all" in mods
    verb = next((_MODIFIER_PHRASES[m] for m in mods if m in _MODIFIER_PHRASES), "is")
    notes = [_MODIFIER_NOTES[m] for m in mods if m in _MODIFIER_NOTES]
    unknown = [m for m in mods if m not in _MODIFIER_PHRASES and m not in _MODIFIER_NOTES and m != "all"]
    notes += [f"modifier `{m}`" for m in unknown]

    if isinstance(value, list) and len(value) > 1:
        quant = "all of" if match_all else "any of"
        vals = f"{quant} " + ", ".join(_q(v) for v in value)
    else:
        vals = _q(value[0] if isinstance(value, list) else value)
    extra = f" ({'; '.join(notes)})" if notes else ""
    return f"`{name}` {verb} {vals}{extra}"


def _detection_lines(name: str, body: Any) -> list[str]:
    if isinstance(body, dict):
        parts = [_field_line(k, v) for k, v in body.items()]
        return [f"- **{name}**: " + (" **and** ".join(parts))]
    if isinstance(body, list) and all(isinstance(x, dict) for x in body):
        lines = [f"- **{name}**: any one of"]
        for alt in body:
            lines.append("  - " + " **and** ".join(_field_line(k, v) for k, v in alt.items()))
        return lines
    if isinstance(body, list):
        return [f"- **{name}**: any keyword anywhere in the event: " + ", ".join(_q(v) for v in body)]
    return [f"- **{name}**: {_q(body)}"]


def _logic_lines(raw_detection: dict) -> list[str]:
    lines: list[str] = []
    for name, body in raw_detection.items():
        if name in ("condition", "timeframe"):
            continue
        lines.extend(_detection_lines(name, body))
    cond = raw_detection.get("condition")
    conds = cond if isinstance(cond, list) else [cond]
    lines.append("- **Condition**: " + " / ".join(f"`{c}`" for c in conds))
    return lines


# ---------------------------------------------------------------------------


def _attack_lines(rule: SigmaRule) -> list[str]:
    """Names come from the pinned ATT&CK index, never from the rule or the model."""
    index = default_index()
    tactics, techniques = [], []
    for t in rule.tags:
        if t.namespace != "attack":
            continue
        if TECHNIQUE_RE.match(t.name):
            tech = index.technique(t.name)
            if tech is None or tech.revoked or tech.deprecated:
                techniques.append(f"- {t.name.upper()}: **not valid in ATT&CK v{index.version}**")
            else:
                techniques.append(f"- [{tech.id}]({tech.url}) {tech.name}")
        elif (tac := index.tactic(t.name)) is not None:
            tactics.append(f"{tac['name']} ({tac['id']})")
    lines = techniques or ["- (none tagged)"]
    if tactics:
        lines.append(f"- Tactic: {', '.join(tactics)}")
    lines += ["", f"Checked against pinned ATT&CK v{index.version} by `ringtail validate`."]
    return lines


def _logsource_line(rule: SigmaRule) -> str:
    ls = rule.logsource
    parts = [f"{k}: `{v}`" for k, v in (("product", ls.product), ("service", ls.service), ("category", ls.category)) if v]
    return ", ".join(parts)


def _esc(s: str) -> str:
    return s.replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;").replace("\n", " ")


def _test_lines(report: RuleReport) -> list[str]:
    tp_ok, tp_n = report.counts("true_positive")
    fp_ok, fp_n = report.counts("false_positive")
    status = "PASS" if report.passed else "FAIL"
    lines = [
        f"**{status}**: {tp_ok}/{tp_n} true-positive samples matched, "
        f"{fp_ok}/{fp_n} false-positive samples correctly ignored.",
        "",
    ]
    for e in report.errors:
        lines.append(f"- Error: {_esc(e)}")
    if report.errors:
        lines.append("")
    lines += ["| Sample | Should fire | Fired | Result |", "|---|---|---|---|"]
    for c in report.cases:
        label = _esc(c.comment) or f"{c.kind}[{c.index}]"
        lines.append(
            f"| {label} | {'yes' if c.expected else 'no'} | {'yes' if c.actual else 'no'} | "
            f"{'pass' if c.passed else '**FAIL**'} |"
        )
    # Fixed repo-relative form so the card doesn't change with the caller's working directory.
    lines += ["", f"Samples: `tests/rules/{report.tests_dir.name}/`"]
    return lines


def render_card(rule_path: Path, notes: CardNotes, report: RuleReport) -> str:
    text = Path(rule_path).read_text(encoding="utf-8")
    rule = SigmaRule.from_yaml(text)
    raw = yaml.safe_load(text)

    out = [
        GENERATED_NOTE.format(id=Path(rule_path).stem),
        f"# {rule.title}",
        "",
        f"`{Path(rule_path).stem}` · Sigma id `{rule.id}` · status `{rule.status}` · level `{rule.level}`",
        "",
        "## Goal",
        "",
        notes.goal,
        "",
        "## ATT&CK",
        "",
        *_attack_lines(rule),
        "",
        "## Log source",
        "",
        _logsource_line(rule),
        "",
        "## Detection logic",
        "",
        notes.summary,
        "",
        "Exact logic, generated from the rule:",
        "",
        *_logic_lines(raw["detection"]),
        "",
        "## Known false positives",
        "",
        *[f"- {fp}" for fp in (rule.falsepositives or ["None documented."])],
        "",
        "## Triage steps",
        "",
        *[f"{i}. {step}" for i, step in enumerate(notes.triage, 1)],
        "",
        "## Test results",
        "",
        *_test_lines(report),
        "",
        "## References",
        "",
        *[f"- <{ref}>" for ref in (rule.references or [])],
        "",
    ]
    return "\n".join(out)


def card_paths(rule_path: Path, cards_dir: Path) -> tuple[Path, Path]:
    stem = Path(rule_path).stem
    return cards_dir / f"{stem}.yml", cards_dir / f"{stem}.md"


def find_cards_dir(rule_path: Path) -> Path:
    for parent in Path(rule_path).resolve().parents:
        if (parent / "cards").is_dir():
            return parent / "cards"
    return Path("cards")


def build_card(rule_path: Path, cards_dir: Path | None = None) -> tuple[Path, str, RuleReport]:
    """Return (card path, rendered markdown, test report). Raises CardNotesError."""
    cards_dir = cards_dir or find_cards_dir(rule_path)
    notes_path, card_path = card_paths(rule_path, cards_dir)
    notes = CardNotes.load(notes_path)
    report = run_rule_tests(Path(rule_path))
    return card_path, render_card(rule_path, notes, report), report
