"""The web backend's logic without HTTP (ADR 0003)."""

import datetime as dt

import pytest

from fakes import EXTRACTION, GOOD_DRAFT, draft
from ringtail import config, service
from ringtail.service import ServiceError

TODAY = dt.date(2026, 11, 18)


def test_info_reports_versions():
    i = service.info()
    assert i["status"] == "ok"
    assert i["attack_version"] == "20.1"
    assert i["max_attempts"] == config.MAX_ATTEMPTS
    assert i["default_model"] == config.DEFAULT_MODEL


def test_extract_prompt_wraps_sanitized_input_as_data():
    p = service.build_prompt({"stage": "extract", "input": "<p>detect <b>encoded</b> powershell</p><script>x()</script>"})
    assert p["stage"] == "extract" and p["purpose"] == "extract"
    assert p["schema"]["required"]
    assert "<untrusted_input" in p["user"]
    assert "detect encoded powershell" in p["user"]
    assert "<script>" not in p["user"] and "x()" not in p["user"]
    assert p["system"].strip()


def test_extract_refuses_an_api_key_in_the_input():
    with pytest.raises(ServiceError, match="API key") as e:
        service.build_prompt({"stage": "extract", "input": "my key is sk-ant-api03-FAKEFAKEFAKE"})
    assert "FAKE" not in str(e.value)


@pytest.mark.parametrize("req, needle", [
    ([], "JSON object"),
    ({"stage": "nope"}, "'stage'"),
    ({"stage": "extract"}, "'input' must be a string"),
    ({"stage": "extract", "input": "   "}, "empty|no readable text"),
    ({"stage": "extract", "input": "x" * 70_000}, "the limit is"),
    ({"stage": "draft"}, "behavior_summary"),
    ({"stage": "draft", "extraction": EXTRACTION, "attempt": 0}, "'attempt'"),
    ({"stage": "draft", "extraction": EXTRACTION, "attempt": 4}, "'attempt'"),
    ({"stage": "draft", "extraction": EXTRACTION, "attempt": True}, "'attempt'"),
    ({"stage": "draft", "extraction": EXTRACTION, "attempt": 2, "previous": "yaml"}, "failed draft object"),
    ({"stage": "draft", "extraction": EXTRACTION, "attempt": 1, "previous": {}}, "only allowed"),
])
def test_bad_prompt_requests_are_refused(req, needle):
    with pytest.raises(ServiceError, match=needle):
        service.build_prompt(req, today=TODAY)


def test_first_draft_prompt_has_code_checked_attack_hints():
    p = service.build_prompt({"stage": "draft", "extraction": EXTRACTION, "attempt": 1})
    assert p["purpose"] == "draft attempt 1"
    assert "T1105: valid" in p["user"]
    assert "slug" in p["schema"]["properties"]


def test_retry_prompt_recomputes_errors_from_the_previous_draft():
    bad = draft(false_positive_events=GOOD_DRAFT["false_positive_events"][1:])
    p = service.build_prompt(
        {"stage": "draft", "extraction": EXTRACTION, "attempt": 2, "previous": bad,
         "errors": ["client-supplied text that must be ignored"]},
        today=TODAY,
    )
    assert "need at least 2 valid false_positive samples" in p["user"]
    assert "client-supplied" not in p["user"]


def test_retry_with_a_passing_previous_draft_is_refused():
    with pytest.raises(ServiceError, match="nothing to retry"):
        service.build_prompt({"stage": "draft", "extraction": EXTRACTION, "attempt": 2, "previous": GOOD_DRAFT},
                             today=TODAY)


def test_check_passes_good_draft_and_renders_card():
    out = service.check({"draft": GOOD_DRAFT}, today=TODAY)
    assert out["passed"] and out["errors"] == []
    r = out["result"]
    assert r["slug"] == "win_proc_certutil_download"
    assert "author: Ringtail draft" in r["rule_yaml"] and "2026-11-18" in r["rule_yaml"]
    assert r["tests"] == {"true_positive": {"passed": 2, "total": 2}, "false_positive": {"passed": 2, "total": 2}}
    assert r["card_markdown"].startswith("<!-- Generated by `ringtail card`")
    assert "tests/rules/win_proc_certutil_download/" in r["card_markdown"]
    assert "**PASS**" in r["card_markdown"]
    assert len(r["card_notes"]["triage"]) == 3
    assert r["card_notes_yaml"].startswith("# AI-drafted card notes")
    assert "Hash the downloaded file." in r["card_notes_yaml"]


def test_retry_without_previous_is_a_fresh_draft():
    p = service.build_prompt({"stage": "draft", "extraction": EXTRACTION, "attempt": 2})
    assert p["purpose"] == "draft attempt 2"


def test_check_reports_exact_errors():
    bad = draft(rule_yaml=GOOD_DRAFT["rule_yaml"].replace("attack.t1105", "attack.t1562.008"))
    out = service.check({"draft": bad}, today=TODAY)
    assert not out["passed"]
    assert any("revoked" in e and "T1685.002" in e for e in out["errors"])
    assert "result" not in out


@pytest.mark.parametrize("req", [None, [], {}, {"draft": "yaml"}])
def test_check_needs_a_draft_object(req):
    with pytest.raises(ServiceError):
        service.check(req)


def test_card_escapes_html_from_model_notes_but_not_code_spans():
    d = draft(card={"goal": "<img src=x onerror=alert(1)> catch it",
                    "summary": "Fires on `<trail>` names.",
                    "triage": ["a", "b", "<script>c</script>"]})
    md = service.check({"draft": d}, today=TODAY)["result"]["card_markdown"]
    assert "<img" not in md and "<script>" not in md
    assert "&lt;img src=x onerror=alert(1)&gt; catch it" in md
    assert "`<trail>`" in md


def test_check_returns_siem_queries():
    r = service.check({"draft": GOOD_DRAFT}, today=TODAY)["result"]
    by_target = {q["target"]: q for q in r["queries"]}
    assert set(by_target) == {"splunk", "kql"}
    assert by_target["kql"]["query"].startswith("DeviceProcessEvents")
    assert "certutil" in by_target["splunk"]["query"].lower()
    assert "## SIEM queries" in r["card_markdown"]
